#!/usr/bin/env python3
"""Optional OFFLINE Chromium DOM checks, not an HTTP/CSP/deployment test.

Requires Playwright + Chromium, not needed by the collector or viewer.
  python -m pip install playwright
  python -m playwright install chromium
  python tests/browser_smoke.py

CHROME_BIN can select an installed Chromium executable. The harness serves the
shipped HTML from a routed, non-existent origin under a repository subpath, so
no request leaves the browser, and mocks fetch with synthetic club datasets. It
removes the CSP only in this test document to permit injecting scripts; shipped
files retain CSP. Screenshots are optional:
  python tests/browser_smoke.py --screenshots /tmp/club-preview
"""
from pathlib import Path
import argparse
import copy
import json
import os
import re
import shutil
import sys
import tempfile
from urllib.parse import quote
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / 'site'
sys.path.insert(0, str(Path(__file__).resolve().parent))
import multiclub_fixtures as f  # noqa: E402

BASE = 'http://viewer.test/EA-FC-pro-club-tracker/'
# Ignores AbortSignal on purpose: a late answer for a club that is no longer
# selected must be dropped by the viewer itself.
MOCK_FETCH = '''({files, delays}) => {
  window.__requests = [];
  window.fetch = async url => {
    const path = new URL(url, document.baseURI).pathname.split('/EA-FC-pro-club-tracker/')[1];
    window.__requests.push(path);
    if (delays[path]) await new Promise(resolve => setTimeout(resolve, delays[path]));
    if (!(path in files)) return {ok: false, status: 404, json: async () => { throw new Error('not JSON'); }};
    return {ok: true, status: 200, json: async () => structuredClone(files[path])};
  };
}'''
CAPTURE_DOWNLOAD = '''() => {
  window.__csv = null; window.__download = null;
  URL.createObjectURL = blob => {blob.text().then(text => window.__csv = text); return 'blob:offline-test';};
  URL.revokeObjectURL = () => {};
  HTMLAnchorElement.prototype.click = function() {window.__download = this.download;};
}'''


def single(payload):
    """A one-club published site for a ready-made dataset."""
    club = payload.get('club') or payload['config']
    return {'data/clubs.json': {'schema_version': 1, 'default_club_id': club['club_id'], 'clubs': [club]},
            f"data/clubs/{club['club_id']}/index.json": payload}


def built_site():
    """The three synthetic clubs, generated by the real collector and site builder."""
    with tempfile.TemporaryDirectory() as directory:
        f.publish(Path(directory))
        data = Path(directory) / 'site' / 'data'
        return {'data/' + path.relative_to(data).as_posix(): json.loads(path.read_bytes())
                for path in data.rglob('*.json')}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--screenshots', type=Path)
    args = parser.parse_args()
    demo = json.loads((SITE / 'demo.json').read_text(encoding='utf-8'))
    # Never depend on or modify a user's real generated archive for the empty test.
    empty = copy.deepcopy(demo)
    empty.update(matches=[], collection={'status': 'not_requested', 'message': 'Synthetic empty fixture.'})
    empty['club'].update(club_name='Empty test club')
    clubs = built_site()
    html = (SITE / 'index.html').read_text(encoding='utf-8')
    html = re.sub(r'<meta http-equiv="Content-Security-Policy"[^>]*>', '', html)
    html = re.sub(r'<script[^>]*src="[^"]+"[^>]*></script>', '', html)
    html = re.sub(r'<link rel="stylesheet"[^>]*>', '', html)
    checks = []

    def check(condition, label):
        if not condition:
            raise AssertionError(label)
        checks.append(label)
        print('PASS:', label)

    with sync_playwright() as pw:
        executable = os.environ.get('CHROME_BIN') or shutil.which('chromium')
        browser = pw.chromium.launch(headless=True, executable_path=executable,
                                     args=['--no-sandbox'])
        errors = []

        def load(files, query='', width=1440, delays=None, context=None, remembered=None, settle='phase !== "loading"'):
            context = context or browser.new_context(viewport={'width': width, 'height': 1080}, device_scale_factor=1)
            page = context.new_page()
            page.on('pageerror', lambda error: errors.append(str(error)))
            page.route('**/*', lambda route: route.fulfill(status=200, content_type='text/html', body=html)
                       if route.request.url.split('?')[0] == BASE else route.abort())
            page.goto(BASE + query)
            page.add_style_tag(content=(SITE / 'assets/style.css').read_text(encoding='utf-8'))
            if remembered is not None:
                page.evaluate('value => localStorage.setItem("dubsfc-tracker.club", value)', remembered)
            page.evaluate(MOCK_FETCH, {'files': files, 'delays': delays or {}})
            for script in ('stats.js', 'clubs.js', 'app.js'):
                page.add_script_tag(content=(SITE / 'assets' / script).read_text(encoding='utf-8'))
            page.wait_for_function(settle)
            return page

        def text(page, selector):
            return page.locator(selector).inner_text()

        def choose(page, club_id, settle=True):
            page.select_option('#club-select', club_id)
            if settle:
                page.wait_for_function('id => phase !== "loading" && club.club_id === id', arg=club_id)

        def settled(page):
            """Loaded cleanly: no leftover loading state and no error notice."""
            return page.evaluate('phase') == 'ready' and not page.locator('#load-error').is_visible() and not page.locator('#collector-health').is_visible()

        def summary(page):
            return (text(page, '#club-name'), text(page, '#match-count'), text(page, '#record'), text(page, '#goals'))

        def table(page, stat):
            """{player name: (cell text, highlighted as column maximum)}."""
            rows = {}
            for row in page.locator('#player-body tr').all():
                cell = row.locator(f'[data-stat="{stat}"]')
                rows[row.locator('.player-name').inner_text()] = (cell.inner_text(), 'column-best' in (cell.get_attribute('class') or ''))
            return rows

        def export_view(page):
            page.evaluate(CAPTURE_DOWNLOAD)
            page.locator('#export-view').click()
            page.wait_for_function('typeof window.__csv === "string"')
            return page.evaluate('[window.__csv, window.__download]')

