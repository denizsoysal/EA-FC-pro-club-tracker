        # ---- Invalid selections ----
        for value in ['999', '../200', '200/../100', 'data/clubs/200', '200/index.json', 'https://example.invalid/x', '<script>', ' 200', '0200']:
            page = load(clubs, '?club=' + quote(value, safe=''), remembered=value)
            check(summary(page)[:2] == ('Alpha United', '3') and page.evaluate('window.__requests') == ['data/clubs.json', 'data/clubs/100/index.json'],
                  f'invalid selection {value!r} falls back to the default and fetches no other path')
