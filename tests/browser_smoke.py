        page.wait_for_function('phase === "ready" && club.club_id === "200"')
        page.wait_for_timeout(900)
        check(summary(page) == ('Beta Town', '2', '1 · 0 · 1', '5 / 3') and 'Alpha Anchor' not in text(page, 'main') and settled(page), 'five quick switches settle on the final club only')
        page.close()

        # ---- Per-club status ----
        status = copy.deepcopy(clubs)
        status['data/clubs/200/index.json']['collection'] = {'status': 'error', 'needs_attention': True, 'message': 'Simulated Beta failure',
                                                            'last_api_attempt_at': '2026-09-30T10:00:00+00:00'}
        page = load(status)
        check(not page.locator('#collector-health').is_visible(), 'a healthy club shows no collector warning')
        choose(page, f.BETA)
        check(page.locator('#collector-health').is_visible() and 'Simulated Beta failure' in text(page, '#health-text') and 'API attempt' in text(page, '#freshness'), 'collection status and last attempt belong to the selected club')
        check(summary(page)[:2] == ('Beta Town', '2'), 'a collection error still shows that club archived matches')
        choose(page, f.ALPHA)
        check(not page.locator('#collector-health').is_visible() and text(page, '#health-text') == '', 'the warning does not follow the viewer to another club')
        page.close()

        # ---- Wrong or missing datasets are never substituted ----
        mixed = copy.deepcopy(clubs)
        mixed['data/clubs/200/index.json'] = copy.deepcopy(clubs['data/clubs/100/index.json'])
        page = load(mixed, '?club=200')
        check(text(page, '#club-name') == 'Beta Town' and 'does not belong to Beta Town' in text(page, '#load-error') and text(page, '#match-count') == '0'
              and 'Alpha Anchor' not in text(page, 'main'), 'a dataset belonging to another club is refused, not displayed')
        choose(page, f.ALPHA)
        check(summary(page)[:2] == ('Alpha United', '3') and not page.locator('#load-error').is_visible() and not page.locator('#collector-health').is_visible(), 'the error clears when a healthy club is selected')
        page.close()
        missing = {name: value for name, value in clubs.items() if name != 'data/clubs/300/index.json'}
        page = load(missing)
        choose(page, f.GAMMA)
        check('HTTP 404' in text(page, '#load-error') and 'could not be loaded' in text(page, '#player-body') and 'Shared Striker' not in text(page, 'main')
              and not page.locator('#export').is_visible(), 'a missing dataset shows an error, never the previous club')
        page.close()
        unconfigured = {'data/clubs.json': {'schema_version': 1, 'default_club_id': '', 'clubs': []}}
        page = load(unconfigured, '?club=100')
        check('No club configured yet' in text(page, '#player-body') and not page.locator('#club-picker').is_visible()
              and page.evaluate('window.__requests') == ['data/clubs.json'], 'no configured club is a setup state without further requests')
        page.close()
        page = load({}, settle='phase === "failed"')
        check('HTTP 404' in text(page, '#load-error') and page.locator('#status-pill').text_content() == 'Data unavailable', 'a missing catalog is reported')
        page.close()

        check(not errors, 'no JavaScript page errors: ' + repr(errors))
        browser.close()
