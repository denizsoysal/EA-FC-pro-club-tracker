        # ---- Rapid switching and late answers ----
        slow = {'data/clubs/200/index.json': 700}
        page = load(clubs, delays=slow)
        choose(page, f.BETA, settle=False)
        check(text(page, '#club-name') == 'Beta Town' and text(page, '#match-count') == '0' and 'Loading Beta Town' in text(page, '#player-body')
              and 'Alpha Anchor' not in text(page, 'main'), 'while a club loads, the previous club numbers are already gone')
        choose(page, f.GAMMA)
        page.wait_for_timeout(1100)
        check(summary(page) == ('Gamma Empty', '0', '—', '—') and 'Beta Runner' not in text(page, 'main') and page.evaluate('club.club_id') == '300'
              and settled(page) and 'No matches archived yet for Gamma Empty' in text(page, '#player-body'),
              'a late answer for an abandoned club does not replace the selected empty club')
        choose(page, f.BETA, settle=False)
        choose(page, f.ALPHA)
        page.wait_for_timeout(1100)
        check(summary(page) == ('Alpha United', '3', '1 · 1 · 1', '4 / 4') and table(page, 'goals') == {'Alpha Anchor': ('3', True), 'Shared Striker': ('1', False)}
              and page.locator('#club-select').input_value() == '100' and 'club=100' in page.url and settled(page), 'rapid switching ends on the last selection with its own data')
